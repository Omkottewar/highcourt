test('one PDF per case replaces atomically and survives backups and changed case identity',t=>{
 const {db,dir}=fixture(t)
 const first=Buffer.from('%PDF-1.7 first'), replacement=Buffer.from('%PDF-1.7 replacement')
 const row=db.create(sample(100,{Title:'ACB',RespondentNumbers:'["2","5"]',PdfName:'first.pdf',PdfBytes:first}))
 assert.equal(Buffer.from(db.pdf(row).bytes).toString(),first.toString())
 db.update(row,{...row,RegdNo:101,PdfName:'replacement.pdf',PdfBytes:replacement})
 assert.equal(db.pdf(row).name,'replacement.pdf')
 assert.throws(()=>db.update(row,{...row,PdfName:'invalid.pdf',PdfBytes:Buffer.from('invalid')}),/valid PDF/)
 assert.equal(db.pdf(row).name,'replacement.pdf')
 assert.equal(db.search().data[0].RegdNo,101)
 const backup=path.join(dir,'pdf-backup.sqlite');db.backup(backup)
 db.restore(backup)
 const restored=db.search().data[0]
 assert.equal(restored.Title,'ACB');assert.equal(restored.RespondentNumbers,'["2","5"]')
 assert.equal(Buffer.from(db.pdf(restored).bytes).toString(),replacement.toString())
 db.delete(restored);assert.equal(db.info().count,0)
})
test('legacy version one databases migrate and restore without losing records',t=>{
 const {db,dir}=fixture(t)
 const {DatabaseSync}=require('node:sqlite')
 const legacy=path.join(dir,'legacy.sqlite'),old=new DatabaseSync(legacy)
 const legacyFields=require('./database.cjs').FIELDS.filter(f=>!['Title','RespondentNumbers','PdfName','CaseNumber','UpdatedAt'].includes(f))
 old.exec(`CREATE TABLE cases (id INTEGER PRIMARY KEY, ${legacyFields.map(f=>`"${f}" TEXT`).join(',')}); PRAGMA application_id=1128549204; PRAGMA user_version=1;`)
 old.prepare('INSERT INTO cases (RegdNo,CYear,Petitioner) VALUES (?,?,?)').run('77','2020','Legacy petitioner');old.close()
 db.restore(legacy);assert.equal(db.search().data[0].Petitioner,'Legacy petitioner')
 const migrated=openRegister(legacy);assert.equal(migrated.search().data[0].Title,null);migrated.close()
})

