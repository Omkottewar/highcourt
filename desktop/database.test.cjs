const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const {openRegister}=require('./database.cjs')
const root=path.join(__dirname,'../.cache/database-tests');fs.mkdirSync(root,{recursive:true})
const sample=(RegdNo, extra={})=>({RegdNo,CYear:'2026',Petitioner:'Alice',District:'Nagpur',Type:'Civil',Dated:'2026-09-26',...extra})
function fixture(t){const dir=fs.mkdtempSync(path.join(root,'run-'));const filename=path.join(dir,'test.sqlite');const db=openRegister(filename);t.after(()=>db.close());return {db,dir,filename}}
test('local writes persist and target one identity; duplicates are rejected',t=>{
 const {db,filename}=fixture(t)
 const a=db.create(sample(921)); db.create(sample(921,{CYear:'2025'}))
 assert.throws(()=>db.create(sample(921)),/UNIQUE/)
 db.update({id:a.id},sample(921,{Petitioner:'Updated'}))
 assert.equal(db.search({query:'Updated'}).count,1)
 db.delete({id:a.id});assert.equal(db.info().count,1)
 const second=openRegister(filename);assert.equal(second.search({},true).data[0].CYear,'2025');second.close()
})
test('filtering, literal characters, pagination and sorting work in SQL',t=>{
 const {db}=fixture(t)
 db.importRows([sample(82,{Petitioner:'Alice 100%_match'}),sample(821,{Dated:'2025-01-01',Adv:'COUNSEL'}),sample(9,{Petitioner:'Bob',Dated:null,District:'Other'})])
 assert.equal(db.search({query:'82',searchField:'RegdNo'}).count,2)
 assert.equal(db.search({query:'82',searchField:'RegdNo',matchMode:'exact'}).count,1)
 assert.equal(db.search({query:'%_'}).count,1)
 assert.equal(db.search({query:"' OR 1=1 --"}).count,0)
 assert.equal(db.search({advocate:'counsel',district:'Nagpur'}).count,1)
 assert.equal(db.search({dateFrom:'2026-01-01'}).count,1)
 const filters={sortField:'RegdNo',sortAsc:true,pageSize:1}
 assert.deepEqual([0,1,2].map(page=>db.search({...filters,page}).data[0].RegdNo),[9,82,821])
 assert.equal(db.search({sortField:'DROP TABLE cases'},true).count,3)
 assert.equal(db.search({},true).data.at(-1).Dated,null)
})
