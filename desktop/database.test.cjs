test('backup and restore preserve records and keep a safety backup; invalid backup cannot erase data',t=>{
 const {db,dir}=fixture(t)
 db.create(sample(1));const backup=path.join(dir,'copy.sqlite');db.backup(backup)
 db.create(sample(2));const result=db.restore(backup)
 assert.equal(db.info().count,1)
 const safety=openRegister(result.safetyBackup);assert.equal(safety.info().count,2);safety.close()
 const invalid=path.join(dir,'invalid.sqlite');fs.writeFileSync(invalid,'not a database')
 assert.throws(()=>db.restore(invalid));assert.equal(db.info().count,1)
 assert.throws(()=>db.backup(db.info().path),/different/)
})

